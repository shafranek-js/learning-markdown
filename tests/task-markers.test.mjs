import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {marked} from 'marked';
import {sanitizeHTML} from '../js/core/sanitize.js';
import {scanTaskMarkers,switchTaskMarker} from '../js/core/task-markers.js';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://example.test/'});
globalThis.DOMParser=dom.window.DOMParser;globalThis.document=dom.window.document;
globalThis.Node=dom.window.Node;globalThis.location=dom.window.location;
const source='- [x] Completed task\n- [ ] Open task\n';
const result=scanTaskMarkers(source);
assert.deepEqual(result.map(x=>x.checked),[true,false]);
assert.equal(switchTaskMarker(source,result[1],true),'- [x] Completed task\n- [x] Open task\n');
assert.equal(switchTaskMarker(source,result[0],false),'- [ ] Completed task\n- [ ] Open task\n');
assert.equal(switchTaskMarker(source,{offset:0,checked:true},false),null);
assert.deepEqual(scanTaskMarkers('- [x] Parent\n  - [ ] Child\n1. [X] Numbered').map(x=>x.checked),[true,false,true]);
assert.deepEqual(scanTaskMarkers('~~~md\n- [x] Sample\n~~~\n- [ ] Actual').map(x=>x.checked),[false]);
assert.deepEqual(scanTaskMarkers('> - [x] Quoted\n> - [ ] Another').map(x=>x.checked),[true,false]);
assert.deepEqual(scanTaskMarkers('\\- [x] Escaped'),[]);
const html=sanitizeHTML(marked.parse(source,{gfm:true}));
const checks=[...new DOMParser().parseFromString(html,'text/html').querySelectorAll('li input')];
assert.deepEqual(checks.map(el=>el.checked),[true,false]);
assert(checks.every(el=>el.disabled));
assert(html.includes('checked=""')&&html.includes('disabled=""'));
assert(!sanitizeHTML('<input type="checkbox" checked onclick="alert(1)">').includes('onclick'));
console.log('PASS: source-mapped GFM tasks, checked HTML serialization and checkbox sanitization');
