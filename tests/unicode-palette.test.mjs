import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {marked} from 'marked';
import {PALETTE_ITEMS,PALETTE_CATEGORIES,PALETTE_TRANSLATIONS,EMOJI_SHORTCODES,searchPalette,paletteLabels} from '../js/core/unicode-palette.js';
import {changeExtension,extensionEnabled,normalizeExtensionSettings} from '../js/core/extensions.js';
const win=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://example.test/'}).window;
Object.assign(globalThis,{DOMParser:win.DOMParser,document:win.document,Node:win.Node,location:win.location,localStorage:{getItem:()=>null,setItem:()=>{}}});
const {state,docKey}=await import('../js/core/state.js');
const {markdownToHTML}=await import('../js/ui/preview.js');
const ids=PALETTE_ITEMS.map(x=>x.id);
assert(PALETTE_ITEMS.length>=65);
assert.equal(new Set(ids).size,ids.length);
assert(PALETTE_CATEGORIES.includes('emoji')&&PALETTE_CATEGORIES.includes('currency'));
assert.equal(searchPalette('euro').find(x=>x.id==='euro').char,'€');
assert.equal(searchPalette('Copyright')[0].char,'©');
assert(searchPalette('стрелка','all','ru').length>=4);
assert(searchPalette('šipky','all','cs').length>=4);
assert.equal(searchPalette('π','math').length,1);
assert.equal(searchPalette('π','emoji').length,0);
assert.equal(searchPalette('<script>').length,0);
assert(searchPalette('','emoji').length>10);
for(const lang of ['en','cs','uk','ro','ru']){
 const labels=paletteLabels(lang);
 assert(labels.trigger&&labels.search&&labels.shortcode&&labels.lessonText&&labels.categoriesLabel&&labels.resultsLabel);
 assert(PALETTE_CATEGORIES.every(cat=>labels[cat]&&PALETTE_TRANSLATIONS[lang][cat]));
}
assert.equal(EMOJI_SHORTCODES.joy,'😂');
assert.equal(EMOJI_SHORTCODES.tent,'⛺');
assert(!Object.hasOwn(EMOJI_SHORTCODES,'script'));
const tick=String.fromCharCode(96);
const source='Before :joy: and :tent: and :unknown:.\n\nCode '+tick+':joy:'+tick+'.\n\n~~~text\n:tent:\n~~~';
const sourceDefault=markdownToHTML(source,'gfm');
assert(sourceDefault.includes(':joy:')&&sourceDefault.includes(':tent:')&&sourceDefault.includes(':unknown:'));
const key=docKey();
state.extensionSettingsByDocument=changeExtension(state.extensionSettingsByDocument,key,'emojiShortcodes',true);
assert(extensionEnabled(state.extensionSettingsByDocument,key,'gfm','emojiShortcodes'));
assert(!extensionEnabled(state.extensionSettingsByDocument,key,'commonmark','emojiShortcodes'));
const rendered=markdownToHTML(source,'gfm');
assert(rendered.includes('😂')&&rendered.includes('⛺')&&rendered.includes(':unknown:'));
const dom=new JSDOM(rendered).window.document;
assert.equal(dom.querySelector('code').textContent,':joy:');
assert(dom.querySelector('pre').textContent.includes(':tent:'));
assert(!markdownToHTML(source,'commonmark').includes('😂'));
assert(!markdownToHTML(source,'original').includes('😂'));
assert(!markdownToHTML(source,'gfm',{extensions:false}).includes('😂'));
assert.equal(normalizeExtensionSettings({sandbox_en:{emojiShortcodes:true}}).sandbox_en.emojiShortcodes,true);
assert.equal(normalizeExtensionSettings({sandbox_en:{emojiShortcodes:'true'}}).sandbox_en,undefined);
state.extensionSettingsByDocument=changeExtension(state.extensionSettingsByDocument,key,'definitionLists',true);
state.extensionSettingsByDocument=changeExtension(state.extensionSettingsByDocument,key,'footnotes',true);
const combined=markdownToHTML('Concept\n: This is :joy:.\n\nMention[^x].\n\n[^x]: Source :heart:.','gfm');
assert(combined.includes('md-definition-list')&&combined.includes('😂')&&combined.includes('❤️')&&combined.includes('md-footnotes'));
assert(!marked.parse(':joy:').includes('😂'));
const hostile=markdownToHTML('Literal :script: and '+tick+'<img onerror="x">'+tick+'\n\n<script>alert(1)</script>','gfm');
assert(!hostile.includes('<script'));
assert([...new JSDOM(hostile).window.document.querySelectorAll('*')].every(el=>
 [...el.attributes].every(attr=>!/^on/i.test(attr.name))),'Event handlers must never survive as HTML attributes');
const unicode='© € → π ✓ 😂';
assert(markdownToHTML(unicode).includes(unicode));
assert(markdownToHTML('Escaped: \\*literal\\* and &copy;').includes('©'));
console.log('PASS: #15 offline Unicode catalogue, multilingual search, opt-in shortcodes and safe composition');
