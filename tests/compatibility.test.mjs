import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {inspectPortability} from '../js/core/compatibility.js';
const environment=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://example.test/'});
globalThis.DOMParser=environment.window.DOMParser;
globalThis.document=environment.window.document;
globalThis.Node=environment.window.Node;
globalThis.location=environment.window.location;
const basic=inspectPortability('# Test heading\n\nA simple **bold** word.');
assert.equal(basic.advanced,false);
assert.equal(basic.gfmDifference,false);
const table=inspectPortability('| A | B |\n| --- | --- |\n| 1 | 2 |');
assert.equal(table.gfmDifference,true);
assert.equal(table.advanced,false);
const styled=inspectPortability('<span class="af-color-blue">Hello</span>');
assert.equal(styled.advanced,true);
const code=inspectPortability('```html\n<span class="af-color-blue">Code only</span>\n```');
assert.equal(code.advanced,false,'Fenced code is not active HTML');
const xss=inspectPortability('<script>window.pwned=true</script>\n\n<u onclick="window.pwned=true" style="color:red">OK</u>');
assert.equal(xss.advanced,true);
assert(!xss.html.includes('script')&&!xss.html.includes('onclick')&&!xss.html.includes('style='));
console.log('PASS: portable Markdown, GFM differences, advanced HTML, inert code and XSS analysis');
