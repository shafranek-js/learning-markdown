import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {headingSlug,addHeadingAnchors,headingOutline,staticMarkdownTOC,isSafeHeadingId} from '../js/core/heading-anchors.js';
import {changeExtension,extensionEnabled} from '../js/core/extensions.js';
const w=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://example.test/'}).window;
Object.assign(globalThis,{DOMParser:w.DOMParser,document:w.document,Node:w.Node,location:w.location,
 localStorage:{getItem:()=>null,setItem:()=>{}}});
const {state,docKey}=await import('../js/core/state.js');
const {markdownToHTML}=await import('../js/ui/preview.js');
const render=(md,dialect='gfm',args)=>new JSDOM(markdownToHTML(md,dialect,args)).window.document;
const getIds=doc=>[...doc.querySelectorAll('h1,h2,h3,h4,h5,h6')].map(el=>el.id);
assert.equal(headingSlug('  Café — Škola  '),'café-škola');
assert.equal(headingSlug('123 first!'),'section-123-first');
assert.equal(headingSlug('!!!'),'section');
assert.equal(headingSlug('Привет, Мир!'),'привет-мир');
assert.equal(headingSlug('中文 标题'),'中文-标题');
assert(!isSafeHeadingId('UPPER'));
assert(!isSafeHeadingId('evil/onload'));
assert(isSafeHeadingId('á-é_русский'));
const md='# Intro\n\n## Details\n\n## Details\n\n### Привет, мир!\n\n#### 42 things\n\n##### !?!';
for(const dialect of ['gfm','commonmark','original']){
 const doc=render(md,dialect);
 assert.deepEqual(getIds(doc),['intro','details','details-2','привет-мир','section-42-things','section'],dialect);
 const outline=headingOutline(doc.body);
 assert.equal(outline.length,6);
 assert(outline.every(row=>row.id&&row.text));
 const toc=staticMarkdownTOC(outline,2);
 assert(toc.includes('- [Intro](#intro)'));
 assert(toc.includes('  - [Details](#details-2)'));
 assert(!toc.includes('привет-мир'));
}
const collision=render('<div id="same">Trusted raw HTML</div>\n\n# Same\n\n# Same');
assert.deepEqual(getIds(collision),['same-2','same-3']);
assert.equal(collision.querySelector('div[id]').id,'same');
const hugeIds=getIds(render(Array.from({length:250},()=>'# Heading').join('\n\n')));
assert.equal(new Set(hugeIds).size,250);
assert(hugeIds.every(isSafeHeadingId));
assert.deepEqual(hugeIds.slice(0,3),['heading','heading-2','heading-3']);
assert(headingSlug('é'.repeat(150)).length<=52);
const malformed=render('# Safe {#foo" onclick="alert(1)}\n\n# Danger <img src="javascript:alert(1)">');
assert([...malformed.body.querySelectorAll('*')].every(el=>
 [...el.attributes].every(attr=>!/^on/i.test(attr.name))),'Event handler attributes must be removed');
assert(!malformed.body.innerHTML.includes('<img'));
assert([...malformed.querySelectorAll('[id]')].every(el=>isSafeHeadingId(el.id)));
const custom='# Title {#my-special-id}\n\n# Again {#my-special-id}\n\n## Второй {#пример}';
assert.notEqual(getIds(render(custom))[0],'my-special-id');
state.extensionSettingsByDocument=changeExtension(state.extensionSettingsByDocument,docKey(),'headingIds',true);
assert(extensionEnabled(state.extensionSettingsByDocument,docKey(),'gfm','headingIds'));
assert(!extensionEnabled(state.extensionSettingsByDocument,docKey(),'commonmark','headingIds'));
const customized=render(custom);
assert.deepEqual(getIds(customized),['my-special-id','my-special-id-2','пример']);
assert.equal(customized.querySelector('h1').textContent.trim(),'Title');
assert.notEqual(getIds(render(custom,'commonmark'))[0],'my-special-id');
assert.notEqual(getIds(render(custom,'original'))[0],'my-special-id');
assert.notEqual(getIds(render(custom,'gfm',{extensions:false}))[0],'my-special-id');
const source='<h2 id="UPPER">Still safe</h2>\n\n# Existing {#safe-id}';
const sanitized=render(source);
assert(!sanitized.body.innerHTML.includes('id="UPPER"'));
assert.equal(getIds(sanitized)[1],'safe-id');
const first=markdownToHTML('# First!\n\n# First!');
assert.equal(addHeadingAnchors(first),first,'Re-applying heading IDs is stable');
assert.equal(staticMarkdownTOC([],6),'');
console.log('PASS: #12 Unicode IDs, 250-heading outlines, 3 dialects, opt-in syntax, XSS and static TOC');
